G = {}


def glyph(ch, *rows, top=0):
    """rows: strings of 6 characters, '#' = ink, starting at glyph row `top`."""
    for r in rows:
        assert len(r) == 6 and set(r) <= {"#", "."}, (ch, r)
    assert top + len(rows) <= 13, ch
    G[ch] = [None] * top + list(rows)


def rep(row, n):
    return [row] * n


