"""Generate Sonar's console font (kernel/drivers/font8x16.h).

An original 8x16 bitmap font drawn for Sonar. Each glyph is 6 pixels wide
and up to 13 rows tall: rows 0-9 hold capitals and digits (the baseline is
under row 9), lowercase letters use rows 3-9 and descenders rows 10-12.
Glyphs are placed at column 1 and row 2 of the 8x16 cell.

  gen_font.py [--preview PNG]
"""
import struct
