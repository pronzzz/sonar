def cell(ch):
    rows = [0] * 16
    for i, r in enumerate(G.get(ch, [])):
        if r is None:
            continue
        bits = 0
        for x, c in enumerate(r):
            if c == "#":
                bits |= 0x80 >> (x + 1)
        rows[2 + i] = bits
    return rows


def main():
    missing = [chr(c) for c in range(32, 128) if chr(c) not in G]
    assert not missing, missing
    out = [
        "/* Generated by tools/gen_font.py: Sonar's original 8x16 console font.",
        " * One byte per row, most significant bit = leftmost pixel. */",
        "#pragma once",
        '#include "types.h"',
        "",
        "static const u8 font8x16[128][16] = {",
    ]
    for c in range(128):
        rows = cell(chr(c)) if c >= 32 else [0] * 16
        label = repr(chr(c)) if 32 <= c < 127 else f"{c}"
        out.append("    { " + ", ".join(f"0x{b:02x}" for b in rows) + " }, /* " + label.replace("*/", "* /") + " */")
    out.append("};")
    with open("kernel/drivers/font8x16.h", "w") as f:
        f.write("\n".join(out) + "\n")

    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        lines = [
            "Sonar 0.1.0 - an operating system with DeepSeek built in",
            "".join(chr(c) for c in range(32, 80)),
            "".join(chr(c) for c in range(80, 127)) + "\x7f",
            "sonar:/$ ? how much disk space is free?  [702 tokens, 7.9 tok/s]",
            "The quick brown fox jumps over the lazy dog. 0O 1lI| {[()]} <=> ~`^",
            "fetch http://10.0.2.2:8765/big.bin /tmp/a.bin  100% 34.3 MiB/s",
        ]
        scale = 2
        w = max(len(l) for l in lines) * 8 * scale
        h = len(lines) * 16 * scale
        px = bytearray(w * h)
        for li, line in enumerate(lines):
            for ci, ch in enumerate(line):
                rows = cell(ch)
                for y in range(16):
                    for x in range(8):
                        if rows[y] & (0x80 >> x):
                            for dy in range(scale):
                                for dx in range(scale):
                                    px[(li * 16 * scale + y * scale + dy) * w + ci * 8 * scale + x * scale + dx] = 255
        raw = b"".join(b"\x00" + bytes(px[y * w:(y + 1) * w]) for y in range(h))

        def chunk(t, d):
            return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)

        png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0))
        png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
        with open(sys.argv[2], "wb") as f:
            f.write(png)


if __name__ == "__main__":
    main()
