#!/usr/bin/env python3
"""Generate kernel/ai/unicode_data.h: codepoint ranges for the Unicode
letter (L*) and number (N*) categories, used by the BPE pre-tokenizer
(the \\p{L} and \\p{N} classes in the GPT-2/Llama-3/Qwen2 split regexes)."""
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(unicodedata.category(chr(cp)))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = [f"static const u32 {name}[][2] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:x},0x{b:x}}}")
        if len(row) == 6:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "kernel/ai/unicode_data.h"
    letters = ranges(lambda c: c.startswith("L"))
    numbers = ranges(lambda c: c.startswith("N"))
    text = [
        "/* Generated by tools/gen_unicode.py from Unicode "
        f"{unicodedata.unidata_version}. Do not edit. */",
        "#pragma once",
        "",
        emit("ucd_letters", letters),
        "",
        emit("ucd_numbers", numbers),
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(text))
    print(f"{out}: {len(letters)} letter ranges, {len(numbers)} number ranges")


if __name__ == "__main__":
    main()
