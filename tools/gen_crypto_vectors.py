#!/usr/bin/env python3
"""Generate tests/host/crypto_vectors.h: expected results computed with the
Python `cryptography` package (OpenSSL), for tests/host/cryptotest.c.

    python3 tools/gen_crypto_vectors.py > tests/host/crypto_vectors.h

Inputs are deterministic, so the file only changes if this script does.
"""
import hashlib
import hmac
import random

from cryptography.hazmat.primitives.asymmetric import ed25519, x25519
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives import poly1305, serialization

rng = random.Random(20261120)


def b(n):
    return bytes(rng.randrange(256) for _ in range(n))


def h(x):
    return '"' + x.hex() + '"'


def raw_pub(k):
    return k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


out = ["/* Generated by tools/gen_crypto_vectors.py; do not edit. */"]

out.append("static const struct { const char *msg, *sha256, *sha512; } hash_vec[] = {")
for n in (0, 1, 3, 55, 56, 63, 64, 65, 111, 112, 119, 120, 127, 128, 129, 200, 1000, 4097):
    m = b(n)
    out.append("    { %s, %s, %s }," % (h(m), h(hashlib.sha256(m).digest()), h(hashlib.sha512(m).digest())))
out.append("};")

out.append("static const struct { const char *key, *msg, *mac; } hmac_vec[] = {")
for kl, ml in ((0, 0), (20, 50), (32, 3), (64, 64), (65, 10), (100, 300)):
    k, m = b(kl), b(ml)
    out.append("    { %s, %s, %s }," % (h(k), h(m), h(hmac.new(k, m, hashlib.sha256).digest())))
out.append("};")


def hkdf(salt, ikm, info, n):
    prk = hmac.new(salt or bytes(32), ikm, hashlib.sha256).digest()
    t, okm, i = b"", b"", 1
    while len(okm) < n:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        okm += t
        i += 1
    return prk, okm[:n]


out.append("static const struct { const char *salt, *ikm, *info, *prk, *okm; } hkdf_vec[] = {")
for sl, il, nl, n in ((13, 22, 10, 42), (0, 22, 0, 42), (32, 32, 40, 32), (5, 80, 200, 100)):
    s, i, info = b(sl), b(il), b(nl)
    prk, okm = hkdf(s, i, info, n)
    out.append("    { %s, %s, %s, %s, %s }," % (h(s), h(i), h(info), h(prk), h(okm)))
out.append("};")

out.append("static const struct { const char *key, *msg, *tag; } poly_vec[] = {")
for n in (0, 1, 15, 16, 17, 32, 63, 64, 100, 1000):
    k, m = b(32), b(n)
    out.append("    { %s, %s, %s }," % (h(k), h(m), h(poly1305.Poly1305.generate_tag(k, m))))
# all-ones message and key edge: h close to p
k = bytes([0xff] * 32)
m = bytes([0xff] * 64)
out.append("    { %s, %s, %s }," % (h(k), h(m), h(poly1305.Poly1305.generate_tag(k, m))))
out.append("};")

out.append("static const struct { const char *key, *nonce, *aad, *pt, *ct; } aead_vec[] = {")
for pl, al in ((0, 0), (1, 0), (15, 5), (16, 13), (17, 13), (64, 0), (65, 21), (300, 5), (1500, 13)):
    k, nonce, aad, pt = b(32), b(12), b(al), b(pl)
    ct = ChaCha20Poly1305(k).encrypt(nonce, pt, aad)
    out.append("    { %s, %s, %s, %s, %s }," % (h(k), h(nonce), h(aad), h(pt), h(ct)))
out.append("};")

out.append("static const struct { const char *a, *pa, *b, *shared; } x25519_vec[] = {")
for _ in range(6):
    ka, kb = (x25519.X25519PrivateKey.from_private_bytes(b(32)),
              x25519.X25519PrivateKey.from_private_bytes(b(32)))
    a = ka.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                         serialization.NoEncryption())
    bb = kb.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                          serialization.NoEncryption())
    out.append("    { %s, %s, %s, %s }," % (h(a), h(raw_pub(ka)), h(bb), h(ka.exchange(kb.public_key()))))
out.append("};")

out.append("static const struct { const char *pub, *msg, *sig; } ed25519_vec[] = {")
for n in (0, 1, 32, 64, 200, 1023):
    k = ed25519.Ed25519PrivateKey.from_private_bytes(b(32))
    m = b(n)
    out.append("    { %s, %s, %s }," % (h(raw_pub(k)), h(m), h(k.sign(m))))
out.append("};")
print("\n".join(out))
